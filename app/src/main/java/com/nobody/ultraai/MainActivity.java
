package com.nobody.ultraai;

import android.os.Bundle;
import android.webkit.WebSettings;
import android.webkit.WebView;
import android.webkit.WebViewClient;
import androidx.appcompat.app.AppCompatActivity;

public class MainActivity extends AppCompatActivity {

    private WebView webView;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        webView = new WebView(this);
        setContentView(webView);

        WebSettings webSettings = webView.getSettings();
        webSettings.setJavaScriptEnabled(true);
        webSettings.setDomStorageEnabled(true);

        webView.setWebViewClient(new WebViewClient());

        // Load NOBODY Ultra AI Dashboard Interface
        String customHtml = "<html><body style='background:#0f172a;color:#f8fafc;font-family:sans-serif;display:flex;justify-content:center;align-items:center;height:100vh;margin:0;'>"
                + "<div style='text-align:center;'>"
                + "<h1 style='color:#38bdf8;'>NOBODY ULTRA AI</h1>"
                + "<p style='color:#94a3b8;'>System Engine & Autonomous Assistant Active</p>"
                + "</div></body></html>";

        webView.loadDataWithBaseURL(null, customHtml, "text/html", "UTF-8", null);
    }
}
